#Rounding Function


print(round(3.14159, 2))  # Output: 3.14
print(round(3.14159, 3))  # Output: 3.142

#Rounding to the nearest integer
print(round(3.14159))  # Output: 3
print(round(3.5))  # Output: 4
print(round(3.4))  # Output: 3

#Rounding to the nearest multiple of 10
print(round(123, -1))  # Output: 120
print(round(127, -1))  # Output: 130
print(round(125, -1))  # Output: 120

#Rounding to the nearest multiple of 100
print(round(1234, -2))  # Output: 1200
print(round(1278, -2))  # Output: 1300
print(round(1250, -2))  # Output: 1200

