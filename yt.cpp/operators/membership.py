#Membership Operators

a=[1,2,3,4,5]
#in operator --> is used to check if a value is present in a sequence
print(3 in a) # True

#not in operator --> is used to check if a value is not present in a sequence
print(6 not in a) # True

#in operator can also be used with strings
s="hello world"
print("world" in s) # True
print("python" not in s) # True

#in operator can also be used with tuples
t=(1,2,3,4,5)
print(3 in t) # True
print(6 not in t) # True

#in operator can also be used with sets
s={1,2,3,4,5}
print(3 in s) # True
print(6 not in s) # True

#in operator can also be used with dictionaries
d={"name":"lokesh","age":25,"city":"delhi"}
print("name" in d) # True
print("python" not in d) # True
print("lokesh" not in d)
print(25 in d)

