#logical and ,or ,not operators
a=10
b=20

 #logical and operator--> is used to check if both conditions are true
print(a>5 and b>15) 

#logical or operator --> is used to check if at least one condition is true
print(a>5 or b<15) 

#logical not operator --> is used to reverse the result of logical operator
print(not(a>5 and b>15))
print(not(a<5 and b>25)) 